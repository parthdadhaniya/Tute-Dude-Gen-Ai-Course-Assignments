# Task 8: Bias and Variance

print("1. What is bias?")
print("- Error from overly simple assumptions (causes underfitting).")

print("\n2. What is variance?")
print("- Sensitivity to training noise (causes overfitting).")

print("\n3. Underfitting and Overfitting:")
print("- High bias, low variance = underfitting.")
print("- Low bias, high variance = overfitting.")

print("\n4. How to reduce overfitting:")
print("- Get more data.")
print("- Limit tree depth.")
print("- Use regularization.")
